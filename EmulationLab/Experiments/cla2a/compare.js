const fs=require('fs');
const root=__dirname,set=process.argv[2]||'candidate-fit1';
const read=f=>JSON.parse(fs.readFileSync(root+'/'+f+'.json'));
const references=[...read('reference-features'),...read('reference-extra-features')];
const candidates=[...read(set+'-features'),...read(set+'-extra-features')];
const rows=references.map(r=>{const c=candidates.find(c=>c.id===r.id);const errors=r.levels.map((l,i)=>c.levels[i].gainDb-l.gainDb);return{id:r.id,g:r.gain,p:r.reduction,rms:Math.sqrt(errors.reduce((s,e)=>s+e*e,0)/errors.length),max:Math.max(...errors.map(Math.abs)),errors};});
const refTiming=read('reference-timing'),canTiming=read(set+'-timing');
const timing=refTiming.map(r=>{const c=canTiming.find(c=>c.pr===r.pr);const errors=r.rows.flatMap((v,j)=>v.reduction.map((x,i)=>c.rows[j].reduction[i]-x));return{pr:r.pr,rms:Math.sqrt(errors.reduce((s,e)=>s+e*e,0)/errors.length),max:Math.max(...errors.map(Math.abs))};});
const quietRef=references.find(r=>r.id==='gain-0.5'),quietCan=candidates.find(r=>r.id==='gain-0.5');
const colour=quietRef.colour.map((v,i)=>({hz:v.frequency,error:quietCan.colour[i].gainDb-v.gainDb}));
const report={levels:rows,timing,colour};
fs.writeFileSync(root+'/'+set+'-comparison.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
